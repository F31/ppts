-- 讲稿分段的画面焦点（G3 焦点落地，2026-11-04）
--
-- 一段话除了「说什么」，还要能说「此刻画面指谁」。这个目标属于讲稿而不是动画规格：
-- 它由内容决定（这句话在讲哪根柱子），与转场/位移无关；放规格里用户要在两个界面各指
-- 一次，而两处会漂。
--
-- 存成一个对象而不是两列（shape_id/bar_id）：目标是一个整体，"有形状没柱子"与
-- "有柱子没形状"都不成立，分成两列就允许了这两种半截状态。NULL = 这段不指任何东西。
--
-- 不加索引：查询永远是按 script_id 整页取（已有 idx_segments_script），没有
-- "按焦点目标反查讲稿"的场景；多一个索引只会让每次整页替换多一次写放大。
