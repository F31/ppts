-- 清理即时任务被写成 0001-01-01 的 run_at（2026-11-08）
--
-- jobs.run_at 的可空语义是「NULL = 立刻可领取」。此前 PG 侧 Create 把
-- time.Time{} 直接交给驱动，于是所有即时任务都落成 0001-01-01 00:00:00+00。
-- 调度判断 (run_at IS NULL OR run_at <= now()) 对零值仍然成立，所以功能上看不出
-- 问题；坏的是读侧：QueueDepthByKind 用 MIN(COALESCE(run_at, created_at)) 报
-- 「最老的待领取任务」，对即时任务会给出公元 1 年——这个判据从此没有意义。
--
-- 判据取 '1970-01-01'：任何真实的退避都不会排到 Unix epoch 之前（退避是小时级），
-- 早于它的值只可能来自零值写入。而这些值的语义与 NULL 完全等价（「不设未来生效
-- 点」），所以直接置 NULL，不必区分具体是哪一个历史零值。
--
-- SQLite profile 不需要对齐：那一侧一直走 sqNullableTime，从未写入零值。
--
-- 执行身份：与 0026 等数据迁移一致，走发布用的 superuser 连接（README：
-- PPTS_MIGRATE_DATABASE_URL）。jobs 是 FORCE ROW LEVEL SECURITY 的表，owner
-- （ppts_migrator）也受策略约束，而这里没有 app.tenant_id 上下文——用普通角色跑
-- 会静默更新 0 行，看起来"成功"，实际上什么都没做。
--
-- 幂等：第二次执行匹配 0 行。条件列上没有可用索引（run_at 是
-- idx_jobs_claim 的第三列），但这是迁移期一次性扫描，可以接受；之后 Create
-- 已经不会再产生这类行。
UPDATE jobs SET run_at = NULL WHERE run_at < '1970-01-01 00:00:00+00';
